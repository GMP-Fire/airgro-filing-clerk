#!/usr/bin/env python3
"""
Filing Clerk — moves document-of-record attachments from Gmail into Google Drive.

Why this exists
---------------
The Cowork scheduled task of the same name could never do this. It reached Drive
through an MCP connector whose create_file takes content only as an inline string,
so every byte of every PDF had to be generated by a language model one token at a
time. A 90 KB statement is ~120,000 base64 characters; it does not fit in a single
tool call, so nothing was ever filed unattended. See size_note in filing-rules.json.

Here the bytes go Gmail API -> this process -> Drive API as a resumable upload.
No model is in the path and there is no practical size limit.

The rule table stays where it already lives: filing-rules.json in Drive, so Andrew
adds a sender without touching this code. Exceptions go to Todoist, never email.
"""

